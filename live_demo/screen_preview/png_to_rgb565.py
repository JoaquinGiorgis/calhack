"""Convert the Figma-exported 320x240 screens into an RGB565 header for the ESP32.

Usage: python png_to_rgb565.py ../../docs/design/screens screens.h
Needs: pip install pillow numpy

Floyd-Steinberg dithering keeps the gradients and glows smooth on the
16-bit display instead of showing colour bands.
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image


def to_rgb565(img: Image.Image) -> np.ndarray:
    a = np.asarray(img.convert("RGB"), dtype=np.float32)
    h, w, _ = a.shape
    levels = np.array([31.0, 63.0, 31.0])
    out = np.zeros((h, w), dtype=np.uint16)
    for y in range(h):
        for x in range(w):
            old = a[y, x]
            q = np.round(np.clip(old, 0, 255) / 255.0 * levels)
            new = q / levels * 255.0
            err = old - new
            if x + 1 < w:
                a[y, x + 1] += err * 7 / 16
            if y + 1 < h:
                if x > 0:
                    a[y + 1, x - 1] += err * 3 / 16
                a[y + 1, x] += err * 5 / 16
                if x + 1 < w:
                    a[y + 1, x + 1] += err * 1 / 16
            r, g, b = int(q[0]), int(q[1]), int(q[2])
            out[y, x] = (r << 11) | (g << 5) | b
    return out


def main(src: str, dst: str) -> None:
    files = sorted(Path(src).glob("*.png"))
    lines = [
        "// Generated by png_to_rgb565.py from docs/design/screens (Figma export). Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    names = []
    for f in files:
        img = Image.open(f)
        if img.size != (320, 240):
            print(f"{f.name} is {img.size[0]}x{img.size[1]}, not a 320x240 screen; skipped")
            continue
        px = to_rgb565(img).flatten()
        ident = "SCREEN_" + f.stem.upper()
        names.append((ident, f.stem))
        lines.append(f"const uint16_t {ident}[320 * 240] = {{")
        for i in range(0, len(px), 16):
            lines.append("  " + ",".join(f"0x{v:04X}" for v in px[i : i + 16]) + ",")
        lines.append("};")
        lines.append("")
        print(f"{f.name} -> {ident}")
    lines.append("struct ScreenImage { const char *name; const uint16_t *pixels; };")
    lines.append("const ScreenImage SCREENS[] = {")
    for ident, stem in names:
        lines.append(f'  {{"{stem}", {ident}}},')
    lines.append("};")
    lines.append(f"const int SCREEN_COUNT = {len(names)};")
    Path(dst).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
