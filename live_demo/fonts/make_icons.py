"""Convert the alert icons exported from Figma (docs/design/icons/*.png, Lucide, ISC) into
20x20 alpha masks for the firmware. Usage: python make_icons.py ../fortwatch_display/icons.h"""
import sys
from pathlib import Path
from PIL import Image

SRC = Path(__file__).resolve().parents[2] / "docs/design/icons"
SIZE = 20

out = ["// Generated by live_demo/fonts/make_icons.py from docs/design/icons (Lucide icons, ISC). Do not edit.",
       "#pragma once", "#include <stdint.h>", "", f"const int ICON_SIZE = {SIZE};", ""]
names = []
for p in sorted(SRC.glob("*.png")):
    a = Image.open(p).convert("RGBA").getchannel("A").resize((SIZE, SIZE), Image.LANCZOS)
    ident = "ICON_" + p.stem.upper()
    names.append((p.stem, ident))
    data = a.tobytes()
    out.append(f"const uint8_t {ident}[{SIZE * SIZE}] = {{")
    for i in range(0, len(data), SIZE):
        out.append("  " + ",".join(str(b) for b in data[i:i + SIZE]) + ",")
    out.append("};")
out += ["", "struct IconMask { const char *name; const uint8_t *alpha; };", "const IconMask ICONS[] = {"]
out += [f'  {{"{n}", {i}}},' for n, i in names]
out += ["};", f"const int ICON_COUNT = {len(names)};", ""]
Path(sys.argv[1]).write_text("\n".join(out))
print(f"{len(names)} icons")
