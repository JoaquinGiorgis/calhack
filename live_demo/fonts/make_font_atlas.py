"""Render Inter (SIL OFL, live_demo/fonts/Inter.ttf) into anti-aliased glyph atlases for the ESP32.

Usage: python make_font_atlas.py ../fortwatch_display/fonts.h      (needs: pip install pillow)

Each glyph is an 8-bit alpha mask; the firmware blends it over the background image
pixel by pixel, so text keeps smooth edges on the Liquid Glass wallpaper.
'\\x7f' is mapped to a middle dot (·) so firmware strings can use it.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = Path(__file__).with_name("Inter.ttf")
# name, weight, size, first char, last char, tracking (px between glyphs)
FONTS = [
    ("F_CLOCK", 300, 62, "0", ":", -2),
    ("F_TITLE", 600, 20, " ", "\x7f", 0),
    ("F_BODY", 500, 13, " ", "\x7f", 0),
    ("F_SMALL", 500, 11, " ", "\x7f", 0),
    ("F_TINY", 500, 10, " ", "\x7f", 0),
]


def load(weight, size):
    f = ImageFont.truetype(str(FONT), size)
    axes = {a["name"]: a for a in f.get_variation_axes()}
    values = []
    for a in f.get_variation_axes():
        n = a["name"]
        if n in (b"Weight", "Weight"):
            values.append(weight)
        elif n in (b"Optical size", b"Optical Size", "Optical size", "Optical Size"):
            values.append(min(max(size, a["minimum"]), a["maximum"]))
        else:
            values.append(a["default"])
    f.set_variation_by_axes(values)
    return f


def render(name, weight, size, first, last, tracking):
    f = load(weight, size)
    ascent, descent = f.getmetrics()
    glyphs, data = [], bytearray()
    for code in range(ord(first), ord(last) + 1):
        ch = "·" if code == 0x7F else chr(code)
        adv = round(f.getlength(ch))
        box = f.getbbox(ch, anchor="ls")  # relative to the baseline origin
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=f, fill=255, anchor="ls")
            off = len(data)
            data += img.tobytes()
        else:
            off = len(data)
        glyphs.append((off, w, h, box[0], box[1], adv))
    return name, first, last, tracking, ascent, descent, glyphs, data


def main(dst):
    out = ["// Generated by live_demo/fonts/make_font_atlas.py from Inter (SIL Open Font License 1.1). Do not edit.",
           "#pragma once", "#include <stdint.h>", "",
           "struct Glyph { uint32_t offset; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; };",
           "struct AtlasFont { const uint8_t *alpha; const Glyph *glyphs; uint8_t first, last; int8_t tracking; uint8_t ascent, descent; };", ""]
    for name, weight, size, first, last, tracking in FONTS:
        n, fst, lst, trk, asc, desc, glyphs, data = render(name, weight, size, first, last, tracking)
        out.append(f"const uint8_t {n}_ALPHA[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        if not data:
            out.append("  0,")
        out.append("};")
        out.append(f"const Glyph {n}_GLYPHS[] = {{")
        for off, w, h, xo, yo, adv in glyphs:
            out.append(f"  {{{off}, {w}, {h}, {xo}, {yo}, {adv}}},")
        out.append("};")
        out.append(f"const AtlasFont {n} = {{{n}_ALPHA, {n}_GLYPHS, {ord(fst)}, {ord(lst)}, {trk}, {asc}, {desc}}};")
        out.append("")
        print(f"{n}: {len(glyphs)} glyphs, {len(data)} bytes")
    Path(dst).write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
